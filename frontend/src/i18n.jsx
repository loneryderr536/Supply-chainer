const read = (k, d) => { try { return localStorage.getItem(k) || d; } catch { return d; } };
const write = (k, v) => { try { localStorage.setItem(k, v); } catch { /* storage unavailable */ } };

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => read('sc.lang', 'en'));
  const [currency, setCurrencyState] = useState(() => read('sc.currency', 'USD'));
  const [fx, setFx] = useState({ rates: { USD: 1 }, source: 'loading' });

  useEffect(() => { api.get('/api/fx').then(setFx).catch(() => {}); }, []);
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);

  const setLang = (l) => { setLangState(l); write('sc.lang', l); };
  const setCurrency = (c) => { setCurrencyState(c); write('sc.currency', c); };
  const locale = (LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0]).locale;

  const t = useCallback((key, vars = {}) => {
    const s = DICTS[lang]?.[key] ?? en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
  }, [lang]);

  const rate = fx.rates?.[currency] ?? (currency === 'USD' ? 1 : null);
  const activeCurrency = rate ? currency : 'USD';
  const money = useCallback((usd) => {
    const value = (usd || 0) * (rate || 1);
    return new Intl.NumberFormat(locale, {
      style: 'currency', currency: activeCurrency,
      maximumFractionDigits: Math.abs(value) >= 1000 || ['JPY', 'INR'].includes(activeCurrency) ? 0 : 2,
    }).format(value);
  }, [rate, activeCurrency, locale]);
  const num = useCallback((v, digits = 1) =>
    new Intl.NumberFormat(locale, { maximumFractionDigits: digits }).format(v), [locale]);
  const toUsd = useCallback((local) => (Number(local) || 0) / (rate || 1), [rate]);

  const value = useMemo(() => ({ lang, setLang, currency: activeCurrency, setCurrency, fx, t, money, num, toUsd, locale }),
    [lang, activeCurrency, fx, t, money, num, toUsd, locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);

// Render the backend's structured explanation in the viewer's language and currency.
export function explain(facts, { t, money, num }) {
  if (!facts) return '';
  const persona = (p) => t(`persona.${p}`);
  const parts = [t('expl.head', {
    mode: t(`legmode.${facts.primary_mode}`), via: facts.chokepoints.join(', ') || t('expl.direct'),
    p50: num(facts.p50_h), p85: num(facts.p85_h), p95: num(facts.p95_h), cost: money(facts.cost_usd),
    basis: facts.cost_basis === 'landed' ? t('card.landed') : t('card.freight'), n: facts.transfers,
  })];
  if (facts.faster_by_h) parts.push(t('expl.faster', { h: num(facts.faster_by_h) }));
  if (facts.slower_by_h) parts.push(t('expl.slower', { h: num(facts.slower_by_h), ref: persona(facts.slower_than) }));
  if (facts.cheaper_by_usd) parts.push(t('expl.cheaper', { c: money(facts.cheaper_by_usd) }));
  if (facts.costlier_by_usd) parts.push(t('expl.costlier', { c: money(facts.costlier_by_usd), ref: persona(facts.costlier_than) }));
  if (facts.avoids?.length) parts.push(t('expl.avoids', { list: facts.avoids.join(', ') }));
  if (facts.scenario_delay_h) parts.push(t('expl.scenario', { h: num(facts.scenario_delay_h) }));
  return parts.join(' ');
}
